def synthesize_voice(text, wav_path):
    clean_text = text.replace('"', '""').replace("'", "''")
    ps_cmd = f"""
    Add-Type -AssemblyName System.Speech
    $synth = New-Object System.Speech.Synthesis.SpeechSynthesizer
    $synth.SelectVoice("Microsoft David Desktop")
    $synth.Rate = 0
    $synth.SetOutputToWaveFile('{wav_path}')
    $synth.Speak("{clean_text}")
    $synth.Dispose()
    """
    subprocess.run(["powershell", "-NoProfile", "-Command", ps_cmd], check=True)

def get_audio_duration(wav_path):
    with wave.open(wav_path, 'r') as wf:
        frames = wf.getnframes()
        rate = wf.getframerate()
        return frames / float(rate)

def build_scene_video(frame_img, audio_wav, out_chunk):
    dur = get_audio_duration(audio_wav) + 0.5 # Add half-second buffer
    cmd = [
        FFMPEG_EXE,
        "-y",
        "-loop", "1",
        "-i", frame_img,
        "-i", audio_wav,
        "-c:v", "libx264",
        "-tune", "stillimage",
        "-c:a", "aac",
        "-b:a", "192k",
        "-pix_fmt", "yuv420p",
        "-t", str(dur),
        "-shortest",
        out_chunk
    ]
    subprocess.run(cmd, check=True)

def main():
    chunk_files = []
    print("Synthesizing audio and compiling scene chunks...")
    for scene in SCENES:
        s_id = scene["id"]
        wav_path = os.path.join(AUDIO_DIR, f"scene_{s_id}.wav")
        chunk_path = os.path.join(CHUNKS_DIR, f"chunk_{s_id}.mp4")
        
        print(f"Processing Scene {s_id}...")
        synthesize_voice(scene["text"], wav_path)
        build_scene_video(scene["frame"], wav_path, chunk_path)
        chunk_files.append(chunk_path)

    # Concat all chunks into final MP4
    concat_list = os.path.join(BASE_DIR, "concat_list.txt")
    with open(concat_list, "w") as f:
        for c in chunk_files:
            # Format for ffmpeg concat
            clean_c = c.replace("\\", "/")
            f.write(f"file '{clean_c}'\n")

    final_mp4 = os.path.join(BASE_DIR, "topic1_autonomous_tdd_loop_audition.mp4")
    print("Concatenating into final MP4 video...")
    concat_cmd = [
        FFMPEG_EXE,
        "-y",
        "-f", "concat",
        "-safe", "0",
        "-i", concat_list,
        "-c", "copy",
        final_mp4
    ]
    subprocess.run(concat_cmd, check=True)
    print(f"SUCCESS: Audition video successfully generated at: {final_mp4}")

if __name__ == "__main__":
    main()
